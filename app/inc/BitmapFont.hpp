inline const char *const *glyphFor(unsigned char c) {
  if (c >= 'a' && c <= 'z')
    c = static_cast<unsigned char>(c - 32);
  if (c < kFirst || c >= kFirst + kCount)
    return nullptr;
  return kRows[c - kFirst];
}

